// 진행 화면에 나오는 모든 문구 (명세 8.3, 8.4, 8.5, 9, 10).
//
// 문구를 고치려면 이 파일만 고치면 된다. 지켜야 하는 선:
//   - STEPS(단계 문구)와 TEXT(안내 문구)는 공개 전에도 화면에 나온다. 어느 앱이 어떤 앱인지,
//     권한을 확인하는지 여부를 말하거나 짐작하게 하는 낱말을 넣지 않는다(명세 8.1).
//     그런 내용은 REVEAL에만 둔다(공개 버튼을 누른 뒤에만 화면으로 나간다).
//   - 단정하지 않는다(명세 13): 같은 연결이라고 항상 접속되는 것은 아니고,
//     실제 서비스에 데이터가 반드시 남는다고도 말하지 않는다.
//   - 2부에는 진단명·분류·점수·등급을 넣지 않는다. 특정 학교·기관을 떠올리게 하는 표현도 넣지 않는다.

function deepFreeze(value) {
  if (value !== null && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const key of Object.keys(value)) deepFreeze(value[key]);
  }
  return value;
}

